"""Core data structures and I/O helpers for LaTeX sources.

The project operates on two closely related kinds of values:

- a named TeX file loaded from disk
- an anonymous TeX buffer generated by a transformation

Keeping both in the same lightweight structure lets library functions return
transformed content today and later attach richer source metadata such as
extents from expanded includes.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True, slots=True)
class TexFile:
    """A LaTeX source buffer plus optional filename metadata.

    ``filename`` is the resolved source file when the buffer comes from disk.
    Generated buffers use ``None``.
    """

    code: str
    filename: Path | None = None

    @classmethod
    def from_path(cls, path: str | Path) -> "TexFile":
        file_path = Path(path).expanduser().resolve()
        return cls(code=file_path.read_text(encoding="utf-8"), filename=file_path)

    @classmethod
    def anonymous(cls, code: str) -> "TexFile":
        return cls(code=code, filename=None)


def read_tex_file(path: str | Path) -> TexFile:
    """Load a TeX file from disk into a :class:`TexFile`."""

    return TexFile.from_path(path)


def write_tex_file(tex_file: TexFile, destination: str | Path | None = None) -> Path:
    """Write ``tex_file`` to ``destination`` or back to its own filename.

    Anonymous buffers must be given an explicit destination.
    """

    if destination is None:
        if tex_file.filename is None:
            raise ValueError("Anonymous TeX buffers require an explicit destination path.")
        output_path = tex_file.filename
    else:
        output_path = Path(destination).expanduser().resolve()

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(tex_file.code, encoding="utf-8")
    return output_path
